// The Word Vault question bank, written for 11th and 12th grade (Seminars in Topics of Literature).
// Two kinds of card alternate through every game:
//   "label": a sentence with one highlighted word. The question is "This highlighted word is..."
//            and the answers are full labels, such as "an abstract noun".
//   "word":  a sentence with no highlight. The question is "Which word in this sentence is a...?"
//            and the answers are words from the sentence.
// Each chamber has 16 cards of each kind (128 in all), so games of 16 or 32 draw from a large pool.
// Every card has exactly one defensible answer: distractors
// never include a label that also fits (for example, "common noun" is never offered beside
// "abstract noun", because an abstract noun is usually common too).
// Quotations are from public-domain works and carry a `source`, which the board shows.

export const CHAMBERS = ['Noun Forge', 'Pronoun Portal', 'Repair Lab', 'Master Lock'];

const article = word => (/^[aeiou]/i.test(word) ? 'an' : 'a');
const withArticle = label => `${article(label)} ${label}`;

// Label card. The first item in `labels` is the correct answer; the game shuffles the order.
function label(id, sector, context, focus, labels, hint, why, discuss, source = '') {
  return {
    id, type: 'label', sector, skill: labels[0],
    prompt: 'This highlighted word is...',
    context, focus, source,
    options: labels.map(withArticle),
    answer: withArticle(labels[0]),
    hint, why, discuss,
  };
}

// Word card. `answer` is a word from the sentence; `distractors` are other words from the sentence.
function word(id, sector, category, context, answer, distractors, hint, why, discuss, source = '') {
  return {
    id, type: 'word', sector, skill: category,
    prompt: `Which word in this sentence is ${article(category)} ${category}?`,
    context, focus: answer, source,
    options: [answer, ...distractors],
    answer,
    hint, why, discuss,
  };
}

